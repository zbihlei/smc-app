def write_signals_log(results_dir, today=None):
    today = today or dt.date.today()
    y = today - dt.timedelta(days=1)
    rows = []

    def add(day, hhmm, kind, sym, d, status, score, price, zl, zh, e, s, t, rr, struct, against="ні", knife="ні", warn=""):
        rows.append([f"{day.isoformat()} {hhmm}", kind, sym, d, status, score, price, zl, zh, e, s, t, rr, 1.2, struct, against,
                     "03.11 12:00", knife, warn])

    # DOGE Short: кілька сканів учора, сьогодні ціна зайшла в зону (наживо)
    for hh in ("10:00", "10:30", "11:00"):
        add(y, hh, "у списку", "DOGEUSDT", "Short", "підхід до зони", 2, 0.0745, 0.0752, 0.07546, 0.07533, 0.07577, 0.07399, 3.05, "вниз (LH+LL)",
            warn="тісний стоп: 0.6% = 0.4× середньої свічки (1.5%)")
    add(today, "09:15", "наживо: ціна в зоні", "DOGEUSDT", "Short", "підхід до зони", 2, 0.07535, 0.0752, 0.07546, 0.07533, 0.07577, 0.07399, 3.05, "вниз (LH+LL)")
    # SUI Short сьогодні
    add(today, "08:00", "у списку", "SUIUSDT", "Short", "підхід до зони", 1, 0.89, 0.9005, 0.906, 0.90325, 0.9104, 0.8722, 3.9, "вниз (LH+LL)",
        knife="так", warn="ніж: різка свічка ×3.4 до звичайної (стоп можуть зняти гнотом)")
    # ETH Long — відсіяно проти структури
    add(today, "08:00", "відсіяно: проти структури 4h", "ETHUSDT", "Long", "підхід до зони", 0, 3500, 3400, 3440, 3420, 3394.9, 3600, 7.2,
        "вниз (LH+LL)", against="так", warn="ПРОТИ структури 4h (немає HH+HL / LH+LL у напрямку)")
    # старий сигнал (20 днів тому) — не має потрапляти в «7 днів»
    add(today - dt.timedelta(days=20), "12:00", "у списку", "BTCUSDT", "Short", "підхід до зони", 3, 79000, 79878.5, 81898.7, 80888.6, 82076.6, 75025, 4.9, "вниз (LH+LL)")
    os.makedirs(results_dir, exist_ok=True)
    with open(os.path.join(results_dir, "signals_log.csv"), "w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f)
        w.writerow(LOG_KEYS)
        w.writerows(rows)
    return rows


