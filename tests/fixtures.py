    _sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    import journal as _J
    jr = _J.Journal(data_dir)
    rows = []
    for (n, d, ins, di, e, s, t, rules, r, man, ch, zone, sup, mfe, scr) in REAL_TRADES:
        rows.append({"row": n + 2, "values": [n, d, ins, di, e, s, t, "", rules, r, man, ch, "", "", "", "", zone, sup,
                                              "" if mfe is None else mfe, scr]})
    jr.import_sheet(rows)
    return jr
